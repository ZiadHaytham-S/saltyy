export function translateText(
  text: string,
  locale: 'ar' | 'en' = 'ar',
): string {
  const key = text.replace(/\s+/g, ' ').trim();
  const value = messages[key];
  if (!value) return text;
  return (
    (text.startsWith(' ') ? ' ' : '') +
    value[locale] +
    (text.endsWith(' ') ? ' ' : '')
  );
}
